fn task_interval_ns(task: &TaskDeclaration) -> Result<i64, CodeGenError> {
    let interval = task
        .properties
        .iter()
        .find(|(name, _)| name.eq_ignore_ascii_case("INTERVAL"))
        .map(|(_, value)| value)
        .ok_or_else(|| CodeGenError {
            message: format!("task {} has no INTERVAL", task.name),
        })?;
    let rendered = emit_expression(interval, &ExpressionContext::default()).map_err(codegen)?;
    rendered
        .strip_suffix("LL")
        .unwrap_or(&rendered)
        .parse()
        .map_err(|_| CodeGenError {
            message: format!("task {} INTERVAL is not a constant TIME", task.name),
        })
}

fn task_priority(task: &TaskDeclaration) -> Result<i64, CodeGenError> {
    let priority = task
        .properties
        .iter()
        .find(|(name, _)| name.eq_ignore_ascii_case("PRIORITY"))
        .map(|(_, value)| value)
        .ok_or_else(|| CodeGenError {
            message: format!("task {} has no PRIORITY", task.name),
        })?;
    literal_i64(priority).ok_or_else(|| CodeGenError {
        message: format!("task {} PRIORITY is not an integer literal", task.name),
    })
}

fn literal_i64(expression: &Expression) -> Option<i64> {
    use crate::frontend::ast::{LiteralType, UnaryOperator};
    match expression {
        Expression::Literal(literal) if literal.literal_type == LiteralType::Int => {
            literal.raw_value.replace('_', "").parse().ok()
        }
        Expression::Unary {
            operator: UnaryOperator::Negate,
            operand,
            ..
        } => literal_i64(operand).map(|value| -value),
        _ => None,
    }
}

fn is_simple_initializer_type(type_ref: &TypeReference) -> bool {
    type_ref.reference_kind == crate::frontend::ast::ReferenceKind::None
        && type_ref.array_dimensions.is_empty()
        && matches!(
            iec_ident(&type_ref.name).as_str(),
            "BOOL"
                | "BYTE"
                | "WORD"
                | "DWORD"
                | "LWORD"
                | "SINT"
                | "INT"
                | "DINT"
                | "LINT"
                | "USINT"
                | "UINT"
                | "UDINT"
                | "ULINT"
                | "REAL"
                | "LREAL"
                | "TIME"
                | "DATE"
                | "TOD"
                | "DT"
                | "STRING"
                | "WSTRING"
        )
}

fn parse_located(name: &str, address: &str, owner: &str) -> Result<LocatedVar, CodeGenError> {
    let bytes = address.as_bytes();
    if bytes.len() < 3 || bytes[0] != b'%' {
        return Err(codegen(format!("invalid located address {address:?}")));
    }
    let area = match bytes[1].to_ascii_uppercase() {
        b'I' => "Input",
        b'Q' => "Output",
        b'M' => "Memory",
        _ => return Err(codegen(format!("invalid located area in {address:?}"))),
    };
    let mut index = 2;
    let size = match bytes.get(index).map(|byte| byte.to_ascii_uppercase()) {
        Some(b'X') => {
            index += 1;
            "Bit"
        }
        Some(b'B') => {
            index += 1;
            "Byte"
        }
        Some(b'W') => {
            index += 1;
            "Word"
        }
        Some(b'D') => {
            index += 1;
            "DWord"
        }
        Some(b'L') => {
            index += 1;
            "LWord"
        }
        _ => "Bit",
    };
    let remainder = &address[index..];
    let (byte, bit) = remainder.split_once('.').unwrap_or((remainder, "0"));
    Ok(LocatedVar {
        name: iec_ident(name),
        address: address.to_owned(),
        area,
        size,
        byte_index: byte
            .parse()
            .map_err(|_| codegen(format!("invalid byte index in {address:?}")))?,
        bit_index: bit
            .parse()
            .map_err(|_| codegen(format!("invalid bit index in {address:?}")))?,
        owner: owner.to_owned(),
    })
}

fn tu_start() -> String {
    let mut out = String::new();
    line(&mut out, BANNER);
    line(&mut out, "");
    line(&mut out, "#include \"generated.hpp\"");
    line(&mut out, "");
    line(&mut out, "namespace strucpp {");
    line(&mut out, "");
    out
}

fn sanitize_file_name(value: &str) -> String {
    value
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || character == '_' {
                character.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect()
}

fn line(out: &mut String, value: &str) {
    out.push_str(value);
    out.push('\n');
}

fn unsupported(message: &str) -> CodeGenError {
    CodeGenError {
        message: format!("unsupported in owned Rust codegen: {message}"),
    }
}

fn codegen(message: impl ToString) -> CodeGenError {
    CodeGenError {
        message: message.to_string(),
    }
}

