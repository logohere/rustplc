const BANNER: &str = "// Generated by STruC++ - IEC 61131-3 Structured Text to C++ Compiler\n// Do not edit this file manually.";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CppFile {
    pub name: String,
    pub content: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodeGenResult {
    pub cpp_files: Vec<CppFile>,
    pub cpp_code: String,
    pub header_code: String,
    pub debug_map: DebugMap,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodeGenError {
    pub message: String,
}

impl fmt::Display for CodeGenError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.message)
    }
}

impl std::error::Error for CodeGenError {}

#[derive(Debug, Clone)]
struct LocatedVar {
    name: String,
    address: String,
    area: &'static str,
    size: &'static str,
    byte_index: u64,
    bit_index: u64,
    owner: String,
}

pub fn generate_cpp(ast: &CompilationUnit) -> Result<CodeGenResult, CodeGenError> {
    generate_cpp_with_libraries(ast, &[], "")
}

pub fn generate_cpp_with_libraries(
    ast: &CompilationUnit,
    libraries: &[StlibArchive],
    program_st: &str,
) -> Result<CodeGenResult, CodeGenError> {
    let mut generator = Generator::new(ast, libraries, program_st, &BTreeMap::new())?;
    generator.generate()
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct LibraryCodegenItem {
    pub name: String,
    pub kind: &'static str,
    pub header: String,
    pub cpp: String,
}

pub(crate) fn generate_library_items(
    ast: &CompilationUnit,
    libraries: &[StlibArchive],
    global_constants: &BTreeMap<String, f64>,
) -> Result<Vec<LibraryCodegenItem>, CodeGenError> {
    let mut generator = Generator::new(ast, libraries, "", global_constants)?;
    let mut items = Vec::new();

    for declaration in generator.types.ordered(&ast.types) {
        let mut header = String::new();
        generator.type_declaration_header(declaration, &mut header)?;
        items.push(LibraryCodegenItem {
            name: iec_ident(&declaration.name),
            kind: "type",
            header,
            cpp: String::new(),
        });
    }
    for interface in &ast.interfaces {
        let mut header = String::new();
        generator.interface_header(interface, &mut header)?;
        items.push(LibraryCodegenItem {
            name: iec_ident(&interface.name),
            kind: "type",
            header,
            cpp: String::new(),
        });
    }
    for block in &ast.global_var_blocks {
        for declaration in &block.declarations {
            let ty = cpp_type_with_registry(&declaration.variable_type, &generator.types)
                .map_err(codegen)?;
            let context = ExpressionContext {
                types: generator.types.clone(),
                ..ExpressionContext::default()
            };
            let initial = declaration
                .initial_value
                .as_ref()
                .map(|value| emit_expression(value, &context))
                .transpose()
                .map_err(codegen)?;
            for name in &declaration.names {
                let emitted = iec_ident(name);
                let header = if let Some(initial) = initial.as_ref() {
                    format!("inline {ty} {emitted}{{{initial}}};\n")
                } else {
                    format!("inline {ty} {emitted}{{}};\n")
                };
                items.push(LibraryCodegenItem {
                    name: emitted,
                    kind: "inlineGlobal",
                    header,
                    cpp: String::new(),
                });
            }
        }
    }
    let ordered_function_blocks = generator
        .ordered_function_blocks()
        .into_iter()
        .cloned()
        .collect::<Vec<_>>();
    for function_block in &ordered_function_blocks {
        let mut header = String::new();
        generator.function_block_header(function_block, &mut header)?;
        let cpp = generator.function_block_cpp(function_block)?;
        items.push(LibraryCodegenItem {
            name: iec_ident(&function_block.name),
            kind: "functionBlock",
            header,
            cpp: strip_translation_unit(&cpp),
        });
    }
    for function in &ast.functions {
        let mut header = String::new();
        generator.function_header(function, &mut header)?;
        let cpp = generator.function_cpp(function)?;
        items.push(LibraryCodegenItem {
            name: iec_ident(&function.name),
            kind: "function",
            header,
            cpp: strip_translation_unit(&cpp),
        });
    }
    Ok(items)
}

fn strip_translation_unit(code: &str) -> String {
    let marker = "namespace strucpp {\n\n";
    let start = code.find(marker).map_or(0, |index| index + marker.len());
    let end = code.rfind("}  // namespace strucpp").unwrap_or(code.len());
    code[start..end].trim_matches('\n').to_owned() + "\n"
}

struct Generator<'a> {
    ast: &'a CompilationUnit,
    libraries: &'a [StlibArchive],
    program_st: &'a str,
    library_fb_types: HashSet<String>,
    library_globals: HashMap<String, String>,
    types: TypeRegistry,
    located: Vec<LocatedVar>,
    loop_counter: usize,
    temp_var_counter: usize,
    loop_stack: Vec<usize>,
    used_loop_labels: HashSet<usize>,
}

impl<'a> Generator<'a> {
    fn new(
        ast: &'a CompilationUnit,
        libraries: &'a [StlibArchive],
        program_st: &'a str,
        global_constants: &BTreeMap<String, f64>,
    ) -> Result<Self, CodeGenError> {
        let mut types = TypeRegistry::new(&ast.types);
        types.register_libraries(libraries);
        types.register_constants(global_constants);
        let library_fb_types = libraries
            .iter()
            .flat_map(|archive| archive.manifest.function_blocks.iter())
            .map(|fb| iec_ident(&fb.name))
            .collect::<HashSet<_>>();
        let library_globals = libraries
            .iter()
            .flat_map(|archive| archive.manifest.globals.iter())
            .map(|global| (iec_ident(&global.name), iec_ident(&global.type_name)))
            .collect::<HashMap<_, _>>();
        let mut this = Self {
            ast,
            libraries,
            program_st,
            library_fb_types,
            library_globals,
            types,
            located: Vec::new(),
            loop_counter: 0,
            temp_var_counter: 0,
            loop_stack: Vec::new(),
            used_loop_labels: HashSet::new(),
        };
        this.collect_located()?;
        Ok(this)
    }

    fn generate(&mut self) -> Result<CodeGenResult, CodeGenError> {
        let header_code = self.header()?;
        let (debug_cpp, debug_map) =
            generate_debug_artifacts(self.ast, &self.types).map_err(codegen)?;
        let mut cpp_files = Vec::new();
        cpp_files.push(CppFile {
            name: "configuration.cpp".to_owned(),
            content: self.configuration_cpp()?,
        });
        cpp_files.push(CppFile {
            name: "generated_debug.cpp".to_owned(),
            content: debug_cpp,
        });
        for function_block in &self.ast.function_blocks {
            cpp_files.push(CppFile {
                name: format!("pou_{}.cpp", iec_ident(&function_block.name)),
                content: self.function_block_cpp(function_block)?,
            });
        }
        for function in &self.ast.functions {
            cpp_files.push(CppFile {
                name: format!("pou_{}.cpp", iec_ident(&function.name)),
                content: self.function_cpp(function)?,
            });
        }
        for program in &self.ast.programs {
            cpp_files.push(CppFile {
                name: format!("pou_{}.cpp", iec_ident(&program.name)),
                content: self.program_cpp(program)?,
            });
        }
        for (archive, chunk) in reachable_chunks(self.libraries, self.program_st) {
            if chunk.cpp.trim().is_empty() {
                continue;
            }
            let mut content = String::new();
            line(&mut content, "#include \"generated.hpp\"");
            line(&mut content, "");
            line(&mut content, "namespace strucpp {");
            line(&mut content, "");
            content.push_str(&chunk.cpp);
            if !content.ends_with('\n') {
                content.push('\n');
            }
            line(&mut content, "}  // namespace strucpp");
            cpp_files.push(CppFile {
                name: format!(
                    "lib_{}_{}.cpp",
                    sanitize_file_name(&archive.manifest.name),
                    sanitize_file_name(&chunk.name)
                ),
                content,
            });
        }
        let cpp_code = cpp_files
            .iter()
            .map(|file| file.content.as_str())
            .collect::<Vec<_>>()
            .join("\n");
        Ok(CodeGenResult {
            cpp_files,
            cpp_code,
            header_code,
            debug_map,
        })
    }

    fn ordered_function_blocks(&self) -> Vec<&FunctionBlockDeclaration> {
        let function_blocks = &self.ast.function_blocks;
        let index_by_name = function_blocks
            .iter()
            .enumerate()
            .map(|(index, function_block)| (iec_ident(&function_block.name), index))
            .collect::<HashMap<_, _>>();
        let dependencies = function_blocks
            .iter()
            .enumerate()
            .map(|(index, function_block)| {
                let mut dependencies = Vec::new();
                if let Some(parent) = function_block.extends.as_deref() {
                    if let Some(parent_index) = index_by_name.get(&iec_ident(parent)).copied() {
                        dependencies.push(parent_index);
                    }
                }
                for block in &function_block.var_blocks {
                    for declaration in &block.declarations {
                        if let Some(dependency_index) = index_by_name
                            .get(&iec_ident(&declaration.variable_type.name))
                            .copied()
                        {
                            if dependency_index != index
                                && !dependencies.contains(&dependency_index)
                            {
                                dependencies.push(dependency_index);
                            }
                        }
                    }
                }
                dependencies
            })
            .collect::<Vec<_>>();
        let mut remaining = (0..function_blocks.len()).collect::<Vec<_>>();
        let mut emitted = HashSet::new();
        let mut order = Vec::new();

        while !remaining.is_empty() {
            let ready = remaining
                .iter()
                .copied()
                .filter(|index| {
                    dependencies[*index]
                        .iter()
                        .all(|dependency| emitted.contains(dependency))
                })
                .collect::<Vec<_>>();
            if ready.is_empty() {
                order.extend(remaining.iter().map(|index| &function_blocks[*index]));
                break;
            }
            for index in ready {
                emitted.insert(index);
                order.push(&function_blocks[index]);
            }
            remaining.retain(|index| !emitted.contains(index));
        }

        order
    }

    fn collect_located(&mut self) -> Result<(), CodeGenError> {
        for program in &self.ast.programs {
            for block in &program.var_blocks {
                if block.block_type == VarBlockType::External {
                    continue;
                }
                for declaration in &block.declarations {
                    let Some(address) = declaration.address.as_deref() else {
                        continue;
                    };
                    for name in &declaration.names {
                        let cpp_name = self
                            .types
                            .member_cpp_name(name, &declaration.variable_type.name);
                        self.located.push(parse_located(
                            &cpp_name,
                            address,
                            &iec_ident(&program.name),
                        )?);
                    }
                }
            }
        }
        for configuration in &self.ast.configurations {
            for block in &configuration.var_blocks {
                if block.block_type != VarBlockType::Global {
                    continue;
                }
                for declaration in &block.declarations {
                    let Some(address) = declaration.address.as_deref() else {
                        continue;
                    };
                    for name in &declaration.names {
                        self.located.push(parse_located(name, address, "@config")?);
                    }
                }
            }
        }
        Ok(())
    }

    fn header(&self) -> Result<String, CodeGenError> {
        let mut out = String::new();
        line(&mut out, "#pragma once");
        line(&mut out, "");
        line(&mut out, BANNER);
        line(&mut out, "");
        for include in [
            "iec_types.hpp",
            "iec_var.hpp",
            "iec_global.hpp",
            "iec_array.hpp",
            "iec_located.hpp",
            "iec_std_lib.hpp",
            "iec_enum.hpp",
            "iec_memory.hpp",
            "iec_pointer.hpp",
            "iec_string.hpp",
            "iec_wstring.hpp",
        ] {
            line(&mut out, &format!("#include \"{include}\""));
        }
        line(&mut out, "#include <array>");
        line(&mut out, "#include <cstddef>");
        line(&mut out, "#include <string>");
        line(&mut out, "");
        line(
            &mut out,
            "// Avoid clashes between ST identifiers and C stdlib macros",
        );
        for name in [
            "TMP_MAX",
            "EOF",
            "BUFSIZ",
            "FOPEN_MAX",
            "FILENAME_MAX",
            "RAND_MAX",
            "EXIT_SUCCESS",
            "EXIT_FAILURE",
        ] {
            line(&mut out, &format!("#ifdef {name}"));
            line(&mut out, &format!("#undef {name}"));
            line(&mut out, "#endif");
        }
        line(&mut out, "");
        line(&mut out, "#undef OVERFLOW");
        line(&mut out, "");
        line(&mut out, "namespace strucpp {");
        line(&mut out, "");

        let library_chunks = reachable_chunks(self.libraries, self.program_st);
        if !library_chunks.is_empty() {
            line(&mut out, "// Imported library chunks");
            for (archive, chunk) in library_chunks {
                line(
                    &mut out,
                    &format!("// Library: {} / {}", archive.manifest.name, chunk.name),
                );
                out.push_str(&chunk.header);
                if !out.ends_with('\n') {
                    out.push('\n');
                }
            }
            line(&mut out, "");
        }

        self.type_declarations_header(&mut out)?;

        for interface in &self.ast.interfaces {
            line(&mut out, &format!("class {};", iec_ident(&interface.name)));
        }
        for function_block in &self.ast.function_blocks {
            line(
                &mut out,
                &format!("class {};", iec_ident(&function_block.name)),
            );
        }
        for program in &self.ast.programs {
            line(
                &mut out,
                &format!("class Program_{};", iec_ident(&program.name)),
            );
        }
        for config in &self.ast.configurations {
            line(
                &mut out,
                &format!("class Configuration_{};", iec_ident(&config.name)),
            );
        }
        if !self.ast.programs.is_empty() || !self.ast.configurations.is_empty() {
            line(&mut out, "");
        }

        self.configuration_globals_header(&mut out)?;
        for interface in &self.ast.interfaces {
            self.interface_header(interface, &mut out)?;
        }
        for function_block in self.ordered_function_blocks() {
            self.function_block_header(function_block, &mut out)?;
        }
        for program in &self.ast.programs {
            self.program_header(program, &mut out)?;
        }
        for function in &self.ast.functions {
            self.function_header(function, &mut out)?;
        }
        for config in &self.ast.configurations {
            self.configuration_header(config, &mut out)?;
        }
        self.located_header(&mut out);
        line(&mut out, "}  // namespace strucpp");
        Ok(out)
    }

    fn type_declarations_header(&self, out: &mut String) -> Result<(), CodeGenError> {
        if self.ast.types.is_empty() {
            return Ok(());
        }
        line(out, "// User-defined types");
        line(out, "");
        for declaration in self.types.ordered(&self.ast.types) {
            self.type_declaration_header(declaration, out)?;
        }
        Ok(())
    }

    fn type_declaration_header(
        &self,
        declaration: &TypeDeclaration,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        let name = iec_ident(&declaration.name);
        match &declaration.definition {
            TypeDefinition::Alias(base) => {
                let raw = raw_type_with_registry(base, &self.types).map_err(codegen)?;
                line(out, &format!("using {name} = {raw};"));
                line(out, "");
                line(out, &alias_iec_wrapper(&name, base, &self.types));
                line(out, "");
            }
            TypeDefinition::Enum {
                base_type, members, ..
            } => {
                let base = base_type
                    .as_ref()
                    .map(|type_ref| raw_type_with_registry(type_ref, &self.types))
                    .transpose()
                    .map_err(codegen)?
                    .map(|base| format!(" : {base}"))
                    .unwrap_or_default();
                let members = members
                    .iter()
                    .map(|member| {
                        let member_name = iec_ident(&member.name);
                        member
                            .value
                            .as_ref()
                            .map(|value| {
                                emit_expression(value, &ExpressionContext::default())
                                    .map(|value| format!("{member_name} = {value}"))
                            })
                            .transpose()
                            .map(|value| value.unwrap_or(member_name))
                    })
                    .collect::<Result<Vec<_>, _>>()
                    .map_err(codegen)?;
                line(
                    out,
                    &format!("enum class {name}{base} {{ {} }};", members.join(", ")),
                );
                line(out, "");
                line(out, &format!("using IEC_{name} = IEC_ENUM<{name}>;"));
                line(out, "");
            }
            TypeDefinition::Struct(fields) => {
                line(out, &format!("struct {name} {{"));
                for field in fields {
                    let cpp_type = struct_field_cpp_type(&field.variable_type, &self.types)
                        .map_err(codegen)?;
                    for field_name in &field.names {
                        let emitted = self
                            .types
                            .member_cpp_name(field_name, &field.variable_type.name);
                        if let Some(initial) = &field.initial_value {
                            let initial = emit_expression(initial, &ExpressionContext::default())
                                .map_err(codegen)?;
                            if cpp_type.starts_with("Array") && initial == "0" {
                                line(out, &format!("    {cpp_type} {emitted}{{}};"));
                            } else {
                                line(out, &format!("    {cpp_type} {emitted} = {initial};"));
                            }
                        } else if field.variable_type.reference_kind
                            == crate::frontend::ast::ReferenceKind::PointerTo
                        {
                            line(out, &format!("    {cpp_type} {emitted} = nullptr;"));
                        } else {
                            line(out, &format!("    {cpp_type} {emitted}{{}};"));
                        }
                    }
                }
                line(out, "};");
                line(out, "");
                line(out, &format!("using IEC_{name} = {name};"));
                line(out, "");
            }
            TypeDefinition::Array {
                dimensions,
                element_type,
            } => {
                let element = struct_field_cpp_type(element_type, &self.types).map_err(codegen)?;
                let array = self
                    .types
                    .format_array_type(&element, dimensions)
                    .map_err(codegen)?;
                line(out, &format!("using {name} = {array};"));
                line(out, "");
                line(out, &format!("using IEC_{name} = {name};"));
                line(out, "");
            }
            TypeDefinition::Subrange {
                base_type,
                lower_bound,
                upper_bound,
            } => {
                let base = raw_type_with_registry(base_type, &self.types).map_err(codegen)?;
                let lower =
                    emit_expression(lower_bound, &ExpressionContext::default()).map_err(codegen)?;
                let upper =
                    emit_expression(upper_bound, &ExpressionContext::default()).map_err(codegen)?;
                line(out, &format!("using {name} = {base};"));
                line(out, &format!("constexpr {base} {name}_MIN = {lower};"));
                line(out, &format!("constexpr {base} {name}_MAX = {upper};"));
                line(out, "");
                line(out, &subrange_iec_wrapper(&name, base_type, &self.types));
                line(out, "");
            }
        }
        Ok(())
    }

    fn configuration_globals_header(&self, out: &mut String) -> Result<(), CodeGenError> {
        let mut seen = HashSet::new();
        let mut emitted = false;
        for config in &self.ast.configurations {
            for block in &config.var_blocks {
                if block.block_type != VarBlockType::Global {
                    continue;
                }
                for declaration in &block.declarations {
                    let ty = cpp_type_with_registry(&declaration.variable_type, &self.types)
                        .map_err(codegen)?;
                    for name in &declaration.names {
                        let name = iec_ident(name);
                        if !seen.insert(name.clone()) {
                            continue;
                        }
                        if !emitted {
                            line(
                                out,
                                "// Configuration VAR_GLOBAL storage — file-scope so every POU (program or nested function block) reaches the one canonical GlobalVar<V> (value + mutex).",
                            );
                            emitted = true;
                        }
                        let type_name = iec_ident(&declaration.variable_type.name);
                        let composite =
                            self.types.is_composite(&type_name)
                                || self.ast.function_blocks.iter().any(|function_block| {
                                    iec_ident(&function_block.name) == type_name
                                });
                        let initial_context = ExpressionContext {
                            types: self.types.clone(),
                            ..ExpressionContext::default()
                        };
                        let initial = declaration
                            .initial_value
                            .as_ref()
                            .map(|value| emit_expression(value, &initial_context))
                            .transpose()
                            .map_err(codegen)?;
                        if let Some(initial) = initial {
                            line(out, &format!("inline GlobalVar<{ty}> {name}{{{initial}}};"));
                        } else if composite {
                            line(out, &format!("inline GlobalVar<{ty}> {name}{{}};"));
                        } else {
                            let initial = default_value(&declaration.variable_type);
                            line(out, &format!("inline GlobalVar<{ty}> {name}{{{initial}}};"));
                        }
                    }
                }
            }
        }
        if emitted {
            line(out, "");
        }
        Ok(())
    }

    fn interface_header(
        &self,
        interface: &InterfaceDeclaration,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        let name = iec_ident(&interface.name);
        let inheritance = if interface.extends.is_empty() {
            String::new()
        } else {
            format!(
                " : {}",
                interface
                    .extends
                    .iter()
                    .map(|parent| format!("public {}", iec_ident(parent)))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        };
        line(out, &format!("class {name}{inheritance} {{"));
        line(out, "public:");
        line(out, &format!("    virtual ~{name}() = default;"));
        for method in &interface.methods {
            let return_type = self.method_return_type(method)?;
            let params = self.method_params(method)?;
            line(
                out,
                &format!(
                    "    virtual {return_type} {}({}) = 0;",
                    iec_ident(&method.name),
                    params.join(", ")
                ),
            );
        }
        line(out, "};");
        line(out, "");
        Ok(())
    }

    fn function_block_header(
        &self,
        function_block: &FunctionBlockDeclaration,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        let types = self.scoped_types(&function_block.var_blocks);
        let name = iec_ident(&function_block.name);
        let mut bases = Vec::new();
        if let Some(parent) = function_block.extends.as_deref() {
            bases.push(format!("public {}", iec_ident(parent)));
        }
        for interface in &function_block.implements {
            bases.push(format!("public {}", iec_ident(interface)));
        }
        let final_spec = if function_block.is_final {
            " final"
        } else {
            ""
        };
        let inheritance = if bases.is_empty() {
            String::new()
        } else {
            format!(" : {}", bases.join(", "))
        };
        line(out, &format!("class {name}{final_spec}{inheritance} {{"));
        line(out, "public:");
        for (block_type, label) in [
            (VarBlockType::Input, "Inputs"),
            (VarBlockType::Output, "Outputs"),
            (VarBlockType::InOut, "In-Out"),
            (VarBlockType::Var, "Local variables"),
            (VarBlockType::Temp, "Local variables"),
            (VarBlockType::Inst, "Local variables"),
        ] {
            let matching = function_block
                .var_blocks
                .iter()
                .filter(|block| block.block_type == block_type)
                .collect::<Vec<_>>();
            if matching.iter().all(|block| block.declarations.is_empty()) {
                continue;
            }
            line(out, &format!("    // {label}"));
            for block in matching {
                for declaration in &block.declarations {
                    let ty = cpp_type_with_registry(&declaration.variable_type, &types)
                        .map_err(codegen)?;
                    for variable in &declaration.names {
                        let variable = self
                            .types
                            .member_cpp_name(variable, &declaration.variable_type.name);
                        line(out, &format!("    {ty} {variable};"));
                    }
                }
            }
        }
        let externals = self.external_vars(&function_block.var_blocks)?;
        if !externals.is_empty() {
            line(
                out,
                "    // External variables (pointers to shared globals)",
            );
            for (name, ty) in &externals {
                line(out, &format!("    GlobalVar<{ty}>* {name} = nullptr;"));
            }
        }

        let var_inst = self.method_var_inst_members(function_block)?;
        if !var_inst.is_empty() {
            line(out, "");
            line(out, "    // Method instance variables (VAR_INST)");
            for (name, ty) in var_inst {
                line(out, &format!("    {ty} {name};"));
            }
        }

        if function_block.extends.is_none() {
            line(out, "");
            line(out, "    // Implicit IEC 61131-3 ENO pin (mirrors EN)");
            line(out, "    IEC_BOOL ENO = true;");
        }
        line(out, "");
        line(out, "    // Constructor");
        line(out, &format!("    {name}();"));
        line(out, "");
        line(out, "    // Execute function block");
        line(out, "    void operator()();");

        if !function_block.methods.is_empty() {
            line(out, "");
            self.method_declarations(&function_block.methods, out)?;
        }
        if !function_block.properties.is_empty() {
            line(out, "");
            self.property_declarations(&function_block.properties, out)?;
        }

        if !function_block.methods.is_empty()
            || !function_block.properties.is_empty()
            || !function_block.is_final
        {
            line(out, "");
            line(out, &format!("    virtual ~{name}() = default;"));
        }
        line(out, "};");
        line(out, "");
        Ok(())
    }

    fn method_return_type(&self, method: &MethodDeclaration) -> Result<String, CodeGenError> {
        let Some(return_type) = method.return_type.as_ref() else {
            return Ok("void".to_owned());
        };
        let mut cpp = cpp_type_with_registry(return_type, &self.types).map_err(codegen)?;
        if self
            .ast
            .interfaces
            .iter()
            .any(|interface| iec_ident(&interface.name) == iec_ident(&return_type.name))
        {
            cpp.push('&');
        }
        Ok(cpp)
    }

    fn method_params(&self, method: &MethodDeclaration) -> Result<Vec<String>, CodeGenError> {
        let types = self.scoped_types(&method.var_blocks);
        let mut params = Vec::new();
        for block in &method.var_blocks {
            if !matches!(
                block.block_type,
                VarBlockType::Input | VarBlockType::Output | VarBlockType::InOut
            ) {
                continue;
            }
            for declaration in &block.declarations {
                let ty =
                    cpp_type_with_registry(&declaration.variable_type, &types).map_err(codegen)?;
                let variable_length_array = declaration
                    .variable_type
                    .array_dimensions
                    .iter()
                    .any(|dimension| dimension.is_variable_length);
                for variable in &declaration.names {
                    let variable = iec_ident(variable);
                    if block.block_type == VarBlockType::Input || variable_length_array {
                        params.push(format!("{ty} {variable}"));
                    } else {
                        params.push(format!("{ty}& {variable}"));
                    }
                }
            }
        }
        Ok(params)
    }

    fn method_declarations(
        &self,
        methods: &[MethodDeclaration],
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        let mut current_visibility = Visibility::Public;
        for visibility in [
            Visibility::Public,
            Visibility::Private,
            Visibility::Protected,
        ] {
            let group = methods
                .iter()
                .filter(|method| method.visibility == visibility)
                .collect::<Vec<_>>();
            if group.is_empty() {
                continue;
            }
            if visibility != current_visibility {
                line(
                    out,
                    match visibility {
                        Visibility::Public => "public:",
                        Visibility::Private => "private:",
                        Visibility::Protected => "protected:",
                    },
                );
                current_visibility = visibility;
            }
            for method in group {
                let return_type = self.method_return_type(method)?;
                let params = self.method_params(method)?;
                let (prefix, suffix) = if method.is_abstract {
                    ("virtual ", " = 0".to_owned())
                } else if method.is_override {
                    (
                        "",
                        if method.is_final {
                            " override final".to_owned()
                        } else {
                            " override".to_owned()
                        },
                    )
                } else {
                    (
                        "virtual ",
                        if method.is_final {
                            " final".to_owned()
                        } else {
                            String::new()
                        },
                    )
                };
                line(
                    out,
                    &format!(
                        "    {prefix}{return_type} {}({}){suffix};",
                        iec_ident(&method.name),
                        params.join(", ")
                    ),
                );
            }
        }
        if current_visibility != Visibility::Public {
            line(out, "public:");
        }
        Ok(())
    }

    fn property_declarations(
        &self,
        properties: &[PropertyDeclaration],
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        line(out, "    // Properties");
        for property in properties {
            let ty =
                cpp_type_with_registry(&property.property_type, &self.types).map_err(codegen)?;
            let name = iec_ident(&property.name);
            if property.getter.is_some() {
                line(out, &format!("    virtual {ty} get_{name}() const;"));
            }
            if property.setter.is_some() {
                line(out, &format!("    virtual void set_{name}({ty} {name});"));
            }
        }
        Ok(())
    }

    fn method_var_inst_members(
        &self,
        function_block: &FunctionBlockDeclaration,
    ) -> Result<Vec<(String, String)>, CodeGenError> {
        let mut members = Vec::new();
        for method in &function_block.methods {
            let mut scoped_blocks = function_block.var_blocks.clone();
            scoped_blocks.extend(method.var_blocks.iter().cloned());
            let types = self.scoped_types(&scoped_blocks);
            for block in &method.var_blocks {
                if block.block_type != VarBlockType::Inst {
                    continue;
                }
                for declaration in &block.declarations {
                    let ty = cpp_type_with_registry(&declaration.variable_type, &types)
                        .map_err(codegen)?;
                    for variable in &declaration.names {
                        members.push((
                            format!("__{}__{}", iec_ident(&method.name), iec_ident(variable)),
                            ty.clone(),
                        ));
                    }
                }
            }
        }
        Ok(members)
    }

    fn function_header(
        &self,
        function: &FunctionDeclaration,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        let types = self.scoped_types(&function.var_blocks);
        let return_type = cpp_type_with_registry(&function.return_type, &types).map_err(codegen)?;
        let params = self.function_params(function)?;
        line(
            out,
            &format!(
                "{return_type} {}({});",
                iec_ident(&function.name),
                params.join(", ")
            ),
        );
        Ok(())
    }

    fn program_header(
        &self,
        program: &ProgramDeclaration,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        let types = self.scoped_types(&program.var_blocks);
        let name = iec_ident(&program.name);
        line(
            out,
            &format!("class Program_{name} : public ProgramBase {{"),
        );
        line(out, "public:");
        if program
            .var_blocks
            .iter()
            .filter(|block| block.block_type != VarBlockType::External)
            .any(|block| !block.declarations.is_empty())
        {
            line(out, "    // Local variables");
        }
        for block in &program.var_blocks {
            if block.block_type == VarBlockType::External {
                continue;
            }
            for declaration in &block.declarations {
                let ty =
                    cpp_type_with_registry(&declaration.variable_type, &types).map_err(codegen)?;
                for variable in &declaration.names {
                    let variable = self
                        .types
                        .member_cpp_name(variable, &declaration.variable_type.name);
                    let constant = if block.is_constant { "const " } else { "" };
                    if let Some(address) = &declaration.address {
                        line(
                            out,
                            &format!("    {constant}{ty} {variable};  // AT {address}"),
                        );
                    } else {
                        line(out, &format!("    {constant}{ty} {variable};"));
                    }
                }
            }
        }
        let externals = self.program_externals(program)?;
        if !externals.is_empty() {
            line(
                out,
                "    // External variables (pointers to shared globals)",
            );
            for (name, ty) in &externals {
                line(out, &format!("    GlobalVar<{ty}>* {name} = nullptr;"));
            }
        }
        line(out, "");
        line(out, "    // Implicit IEC 61131-3 ENO pin (mirrors EN)");
        line(out, "    IEC_BOOL ENO = true;");
        line(out, "");
        line(out, "    // Constructor");
        if externals.is_empty() {
            line(out, &format!("    Program_{name}();"));
        } else {
            let params = externals
                .iter()
                .map(|(name, ty)| format!("GlobalVar<{ty}>* {name}_ref"))
                .collect::<Vec<_>>()
                .join(", ");
            line(out, &format!("    explicit Program_{name}({params});"));
        }
        line(out, "");
        line(out, "    // Run program");
        line(out, "    void run() override;");
        if let Some((offset, count)) = self.located_range(&name) {
            line(out, "");
            line(out, "#ifdef STRUCPP_THREADED");
            line(
                out,
                &format!(
                    "    void located_range(uint32_t* __off, uint32_t* __cnt) const override {{ *__off = {offset}; *__cnt = {count}; }}"
                ),
            );
            line(out, "#endif");
        }
        line(out, "};");
        line(out, "");
        Ok(())
    }

    fn configuration_header(
        &self,
        config: &ConfigurationDeclaration,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        let name = iec_ident(&config.name);
        let instances = collect_instances(config);
        line(
            out,
            &format!("class Configuration_{name} : public ConfigurationInstance {{"),
        );
        line(out, "public:");
        if !instances.is_empty() {
            line(out, "    // Program instances");
            for instance in &instances {
                line(
                    out,
                    &format!(
                        "    Program_{} {};",
                        iec_ident(&instance.program_type),
                        iec_ident(&instance.instance_name)
                    ),
                );
            }
            line(out, "");
        }
        let task_count: usize = config.resources.iter().map(|r| r.tasks.len()).sum();
        if task_count > 0 {
            line(out, "    // Task storage");
            line(
                out,
                &format!("    TaskInstance tasks_storage[{task_count}];"),
            );
            line(
                out,
                &format!(
                    "    ProgramBase* task_programs_storage[{}];",
                    instances.len().max(1)
                ),
            );
        }
        if !config.resources.is_empty() {
            line(out, "    // Resource storage");
            line(
                out,
                &format!(
                    "    ResourceInstance resources_storage[{}];",
                    config.resources.len()
                ),
            );
        }
        line(out, "");
        line(out, "    // Constructor");
        line(out, &format!("    Configuration_{name}();"));
        line(out, "");
        line(out, "    // ConfigurationInstance interface");
        line(out, "    const char* get_name() const override;");
        line(out, "    ResourceInstance* get_resources() override;");
        line(out, "    size_t get_resource_count() const override;");
        line(out, "};");
        line(out, "");
        Ok(())
    }

    fn located_header(&self, out: &mut String) {
        if self.ast.programs.is_empty() {
            return;
        }
        line(
            out,
            "// =============================================================================",
        );
        line(out, "// Located Variables Descriptor Array");
        line(
            out,
            "// =============================================================================",
        );
        line(out, "");
        line(out, "/**");
        line(
            out,
            " * Located variable descriptors for runtime I/O binding.",
        );
        line(
            out,
            " * The runtime iterates this array to bind variables to I/O image tables.",
        );
        line(out, " */");
        line(out, "");
        if self.located.is_empty() {
            line(out, "// (no located variables — placeholder entry only)");
        } else {
            for located in &self.located {
                let owner = if located.owner == "@config" {
                    "configuration".to_owned()
                } else {
                    format!("Program_{}", located.owner)
                };
                line(
                    out,
                    &format!(
                        "// Forward: {} AT {} in {owner}",
                        located.name, located.address
                    ),
                );
            }
        }
        line(out, "");
        line(
            out,
            &format!(
                "extern LocatedVar locatedVars[{}];",
                self.located.len().max(1)
            ),
        );
        line(
            out,
            &format!(
                "constexpr uint32_t locatedVarsCount = {};",
                self.located.len()
            ),
        );
        line(out, "");
        let global_count = self
            .located
            .iter()
            .filter(|located| located.owner == "@config")
            .count();
        line(out, "#ifdef STRUCPP_THREADED");
        line(
            out,
            &format!("extern void *locatedGlobals[{}];", global_count.max(1)),
        );
        line(
            out,
            &format!("constexpr uint32_t locatedGlobalsCount = {global_count};"),
        );
        line(out, "#endif");
        line(out, "");
    }

    fn configuration_cpp(&self) -> Result<String, CodeGenError> {
        let mut out = tu_start();
        self.located_definition(&mut out);
        for config in &self.ast.configurations {
            self.configuration_implementation(config, &mut out)?;
        }
        line(&mut out, "}  // namespace strucpp");
        Ok(out)
    }

    fn located_definition(&self, out: &mut String) {
        if self.ast.programs.is_empty() {
            return;
        }
        line(
            out,
            "// =============================================================================",
        );
        line(out, "// Located Variables Descriptor Array");
        line(
            out,
            "// =============================================================================",
        );
        line(out, "");
        line(
            out,
            &format!("LocatedVar locatedVars[{}] = {{", self.located.len().max(1)),
        );
        if self.located.is_empty() {
            line(
                out,
                "    { LocatedArea::Input, LocatedSize::Bit, 0, 0, {0, 0, 0}, nullptr }  // placeholder; locatedVarsCount is 0",
            );
        } else {
            for (index, located) in self.located.iter().enumerate() {
                let comma = if index + 1 == self.located.len() {
                    ""
                } else {
                    ","
                };
                line(
                    out,
                    &format!(
                        "    {{ LocatedArea::{}, LocatedSize::{}, {}, {}, {{0, 0, 0}}, nullptr }}{comma}  // {} AT {}",
                        located.area,
                        located.size,
                        located.byte_index,
                        located.bit_index,
                        located.name,
                        located.address
                    ),
                );
            }
        }
        line(out, "};");
        line(out, "");
        let globals = self
            .located
            .iter()
            .filter(|located| located.owner == "@config")
            .collect::<Vec<_>>();
        line(out, "#ifdef STRUCPP_THREADED");
        line(
            out,
            "// Canonical storage pointers of the located CONFIGURATION VAR_GLOBALs.",
        );
        line(
            out,
            "// Populated in the configuration constructor (like locatedVars[] above).",
        );
        line(
            out,
            &format!("void *locatedGlobals[{}] = {{", globals.len().max(1)),
        );
        if globals.is_empty() {
            line(out, "    nullptr  // placeholder; locatedGlobalsCount is 0");
        } else {
            for (index, global) in globals.iter().enumerate() {
                let comma = if index + 1 == globals.len() { "" } else { "," };
                line(
                    out,
                    &format!(
                        "    nullptr{comma}  // {} AT {}",
                        global.name, global.address
                    ),
                );
            }
        }
        line(out, "};");
        line(out, "");
        line(
            out,
            "// C linkage: a host runtime is built once and loads many .so files, so it",
        );
        line(
            out,
            "// cannot reach namespaced C++ symbols by mangled name portably.",
        );
        line(
            out,
            "extern \"C\" void *const *strucpp_get_located_globals(void) { return locatedGlobals; }",
        );
        line(
            out,
            "extern \"C\" uint32_t strucpp_get_located_global_count(void) { return locatedGlobalsCount; }",
        );
        line(out, "#endif  // STRUCPP_THREADED");
        line(out, "");
    }

    fn configuration_implementation(
        &self,
        config: &ConfigurationDeclaration,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        let config_name = iec_ident(&config.name);
        let instances = collect_instances(config);
        line(
            out,
            &format!("Configuration_{config_name}::Configuration_{config_name}()"),
        );
        let mut initializers = Vec::new();
        for instance in &instances {
            let program = self
                .ast
                .programs
                .iter()
                .find(|program| iec_ident(&program.name) == iec_ident(&instance.program_type))
                .ok_or_else(|| CodeGenError {
                    message: format!(
                        "configuration references unknown program {}",
                        instance.program_type
                    ),
                })?;
            let externals = self.program_externals(program)?;
            let args = externals
                .iter()
                .map(|(name, _)| format!("&{name}"))
                .collect::<Vec<_>>()
                .join(", ");
            initializers.push(format!("{}({args})", iec_ident(&instance.instance_name)));
        }
        if !initializers.is_empty() {
            line(out, &format!("    : {}", initializers.join(", ")));
        }
        line(out, "{");
        line(out, "    // Wire up tasks and resources");
        let mut task_index = 0usize;
        let mut program_index = 0usize;
        for (resource_index, resource) in config.resources.iter().enumerate() {
            let resource_task_start = task_index;
            for task in &resource.tasks {
                let task_program_start = program_index;
                let task_name = iec_ident(&task.name);
                let assigned = resource
                    .program_instances
                    .iter()
                    .filter(|instance| {
                        instance
                            .task_name
                            .as_deref()
                            .is_some_and(|candidate| iec_ident(candidate) == task_name)
                    })
                    .collect::<Vec<_>>();
                for instance in &assigned {
                    line(
                        out,
                        &format!(
                            "    task_programs_storage[{program_index}] = &{};",
                            iec_ident(&instance.instance_name)
                        ),
                    );
                    program_index += 1;
                }
                line(
                    out,
                    &format!(
                        "    tasks_storage[{task_index}] = TaskInstance(\"{task_name}\", {}LL, {}, &task_programs_storage[{task_program_start}], {});",
                        task_interval_ns(task)?,
                        task_priority(task)?,
                        assigned.len()
                    ),
                );
                task_index += 1;
            }
            line(
                out,
                &format!(
                    "    resources_storage[{resource_index}] = ResourceInstance(\"{}\", \"{}\", &tasks_storage[{resource_task_start}], {});",
                    iec_ident(&resource.name),
                    iec_ident(&resource.on_type),
                    resource.tasks.len()
                ),
            );
        }
        let globals = self
            .located
            .iter()
            .enumerate()
            .filter(|(_, located)| located.owner == "@config")
            .collect::<Vec<_>>();
        if !globals.is_empty() {
            line(out, "    // Initialize located variable pointers");
            for (index, located) in &globals {
                line(
                    out,
                    &format!(
                        "    locatedVars[{index}].pointer = {}.value.raw_ptr();",
                        located.name
                    ),
                );
            }
            line(out, "#ifdef STRUCPP_THREADED");
            line(out, "    // Initialize located-global pointers");
            for (global_index, (_, located)) in globals.iter().enumerate() {
                line(
                    out,
                    &format!(
                        "    locatedGlobals[{global_index}] = {}.value.raw_ptr();",
                        located.name
                    ),
                );
            }
            line(out, "#endif");
        }
        line(out, "}");
        line(out, "");
        line(
            out,
            &format!("const char* Configuration_{config_name}::get_name() const {{"),
        );
        line(out, &format!("    return \"{config_name}\";"));
        line(out, "}");
        line(out, "");
        line(
            out,
            &format!("ResourceInstance* Configuration_{config_name}::get_resources() {{"),
        );
        line(out, "    return resources_storage;");
        line(out, "}");
        line(out, "");
        line(
            out,
            &format!("size_t Configuration_{config_name}::get_resource_count() const {{"),
        );
        line(out, &format!("    return {};", config.resources.len()));
        line(out, "}");
        line(out, "");
        Ok(())
    }

    fn function_block_cpp(
        &mut self,
        function_block: &FunctionBlockDeclaration,
    ) -> Result<String, CodeGenError> {
        let mut out = tu_start();
        let name = iec_ident(&function_block.name);
        let context = self.function_block_context(function_block, &[], None)?;
        let mut initializers = Vec::new();
        for block in &function_block.var_blocks {
            if block.block_type == VarBlockType::External {
                for declaration in &block.declarations {
                    for variable in &declaration.names {
                        let global = iec_ident(variable);
                        let member = self
                            .types
                            .member_cpp_name(variable, &declaration.variable_type.name);
                        initializers.push(format!("{member}(&strucpp::{global})"));
                    }
                }
                continue;
            }
            for declaration in &block.declarations {
                if !is_simple_initializer_type(&declaration.variable_type) {
                    continue;
                }
                if let Some(initial) = &declaration.initial_value {
                    let initial = emit_expression(initial, &context).map_err(codegen)?;
                    for variable in &declaration.names {
                        let variable = self
                            .types
                            .member_cpp_name(variable, &declaration.variable_type.name);
                        initializers.push(format!("{variable}({initial})"));
                    }
                }
            }
        }
        if initializers.is_empty() {
            line(&mut out, &format!("{name}::{name}() {{"));
        } else {
            line(&mut out, &format!("{name}::{name}()"));
            line(&mut out, &format!("    : {}", initializers.join(", ")));
            line(&mut out, "{");
        }
        line(&mut out, "    // Initialize variables");
        line(&mut out, "}");
        line(&mut out, "");
        line(&mut out, &format!("void {name}::operator()() {{"));
        self.statements(&function_block.body, &context, "    ", &mut out)?;
        line(&mut out, "}");
        line(&mut out, "");

        for method in &function_block.methods {
            if method.is_abstract {
                continue;
            }
            self.method_cpp(function_block, method, &mut out)?;
        }
        for property in &function_block.properties {
            self.property_cpp(function_block, property, &mut out)?;
        }

        line(&mut out, "}  // namespace strucpp");
        Ok(out)
    }

    fn method_cpp(
        &mut self,
        function_block: &FunctionBlockDeclaration,
        method: &MethodDeclaration,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        let mut scoped_blocks = function_block.var_blocks.clone();
        scoped_blocks.extend(method.var_blocks.iter().cloned());
        let types = self.scoped_types(&scoped_blocks);
        let class_name = iec_ident(&function_block.name);
        let method_name = iec_ident(&method.name);
        let return_type = self.method_return_type(method)?;
        let params = self.method_params(method)?;
        let function_name = method.return_type.as_ref().map(|_| method_name.as_str());
        let mut context =
            self.function_block_context(function_block, &method.var_blocks, function_name)?;
        for block in &method.var_blocks {
            if block.block_type != VarBlockType::Inst {
                continue;
            }
            for declaration in &block.declarations {
                for variable in &declaration.names {
                    context.variable_cpp_names.insert(
                        iec_ident(variable),
                        format!("__{}__{}", method_name, iec_ident(variable)),
                    );
                }
            }
        }

        line(
            out,
            &format!(
                "{return_type} {class_name}::{method_name}({}) {{",
                params.join(", ")
            ),
        );
        if method.return_type.is_some() {
            line(out, &format!("    {return_type} {method_name}_result;"));
        }
        for block in &method.var_blocks {
            if !matches!(block.block_type, VarBlockType::Var | VarBlockType::Temp) {
                continue;
            }
            for declaration in &block.declarations {
                let ty =
                    cpp_type_with_registry(&declaration.variable_type, &types).map_err(codegen)?;
                for variable in &declaration.names {
                    let variable = iec_ident(variable);
                    if let Some(initial) = &declaration.initial_value {
                        line(
                            out,
                            &format!(
                                "    {ty} {variable} = {};",
                                emit_expression(initial, &context).map_err(codegen)?
                            ),
                        );
                    } else {
                        line(out, &format!("    {ty} {variable};"));
                    }
                }
            }
        }
        self.statements(&method.body, &context, "    ", out)?;
        if method.return_type.is_some() {
            line(out, &format!("    return {method_name}_result;"));
        }
        line(out, "}");
        line(out, "");
        Ok(())
    }

    fn property_cpp(
        &mut self,
        function_block: &FunctionBlockDeclaration,
        property: &PropertyDeclaration,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        let class_name = iec_ident(&function_block.name);
        let property_name = iec_ident(&property.name);
        let ty = cpp_type_with_registry(&property.property_type, &self.types).map_err(codegen)?;
        if let Some(getter) = property.getter.as_ref() {
            let context = self.function_block_context(function_block, &[], Some(&property_name))?;
            line(
                out,
                &format!("{ty} {class_name}::get_{property_name}() const {{"),
            );
            line(out, &format!("    {ty} {property_name}_result;"));
            self.statements(getter, &context, "    ", out)?;
            line(out, &format!("    return {property_name}_result;"));
            line(out, "}");
            line(out, "");
        }
        if let Some(setter) = property.setter.as_ref() {
            let mut context = self.function_block_context(function_block, &[], None)?;
            context.variable_types.insert(
                property_name.clone(),
                iec_ident(&property.property_type.name),
            );
            line(
                out,
                &format!("void {class_name}::set_{property_name}({ty} {property_name}) {{"),
            );
            self.statements(setter, &context, "    ", out)?;
            line(out, "}");
            line(out, "");
        }
        Ok(())
    }

    fn function_cpp(&mut self, function: &FunctionDeclaration) -> Result<String, CodeGenError> {
        let mut out = tu_start();
        let types = self.scoped_types(&function.var_blocks);
        let name = iec_ident(&function.name);
        let return_type = cpp_type_with_registry(&function.return_type, &types).map_err(codegen)?;
        let params = self.function_params(function)?;
        let context = self.context_for_blocks(&function.var_blocks, Some(&name))?;
        line(
            &mut out,
            &format!("{return_type} {name}({}) {{", params.join(", ")),
        );
        line(&mut out, &format!("    {return_type} {name}_result;"));
        for block in &function.var_blocks {
            if !matches!(block.block_type, VarBlockType::Var | VarBlockType::Temp) {
                continue;
            }
            for declaration in &block.declarations {
                let ty =
                    cpp_type_with_registry(&declaration.variable_type, &types).map_err(codegen)?;
                for variable in &declaration.names {
                    let variable = self
                        .types
                        .member_cpp_name(variable, &declaration.variable_type.name);
                    if let Some(initial) = &declaration.initial_value {
                        line(
                            &mut out,
                            &format!(
                                "    {ty} {variable} = {};",
                                emit_expression(initial, &context).map_err(codegen)?
                            ),
                        );
                    } else {
                        line(&mut out, &format!("    {ty} {variable};"));
                    }
                }
            }
        }
        self.statements(&function.body, &context, "    ", &mut out)?;
        line(&mut out, &format!("    return {name}_result;"));
        line(&mut out, "}");
        line(&mut out, "");
        line(&mut out, "}  // namespace strucpp");
        Ok(out)
    }

    fn function_params(&self, function: &FunctionDeclaration) -> Result<Vec<String>, CodeGenError> {
        let types = self.scoped_types(&function.var_blocks);
        let mut params = Vec::new();
        for block in &function.var_blocks {
            if !matches!(
                block.block_type,
                VarBlockType::Input | VarBlockType::Output | VarBlockType::InOut
            ) {
                continue;
            }
            for declaration in &block.declarations {
                let ty =
                    cpp_type_with_registry(&declaration.variable_type, &types).map_err(codegen)?;
                let variable_length_array = declaration
                    .variable_type
                    .array_dimensions
                    .iter()
                    .any(|dimension| dimension.is_variable_length);
                for variable in &declaration.names {
                    let variable = self
                        .types
                        .member_cpp_name(variable, &declaration.variable_type.name);
                    if block.block_type == VarBlockType::Input || variable_length_array {
                        params.push(format!("{ty} {variable}"));
                    } else {
                        params.push(format!("{ty}& {variable}"));
                    }
                }
            }
        }
        Ok(params)
    }

    fn program_cpp(&mut self, program: &ProgramDeclaration) -> Result<String, CodeGenError> {
        let mut out = tu_start();
        let name = iec_ident(&program.name);
        let context = self.expression_context(program)?;
        let externals = self.program_externals(program)?;
        if externals.is_empty() {
            line(&mut out, &format!("Program_{name}::Program_{name}()"));
        } else {
            let params = externals
                .iter()
                .map(|(name, ty)| format!("GlobalVar<{ty}>* {name}_ref"))
                .collect::<Vec<_>>()
                .join(", ");
            line(
                &mut out,
                &format!("Program_{name}::Program_{name}({params})"),
            );
        }
        let mut initializers = Vec::new();
        for block in &program.var_blocks {
            if block.block_type == VarBlockType::External {
                continue;
            }
            for declaration in &block.declarations {
                if !is_simple_initializer_type(&declaration.variable_type) {
                    continue;
                }
                let initial = declaration
                    .initial_value
                    .as_ref()
                    .map(|value| emit_expression(value, &context))
                    .transpose()
                    .map_err(codegen)?
                    .unwrap_or_else(|| default_value(&declaration.variable_type));
                for variable in &declaration.names {
                    let variable = self
                        .types
                        .member_cpp_name(variable, &declaration.variable_type.name);
                    initializers.push(format!("{variable}({initial})"));
                }
            }
        }
        initializers.extend(
            externals
                .iter()
                .map(|(name, _)| format!("{name}({name}_ref)")),
        );
        if !initializers.is_empty() {
            line(&mut out, &format!("    : {}", initializers.join(", ")));
        }
        line(&mut out, "{");
        let located = self
            .located
            .iter()
            .enumerate()
            .filter(|(_, located)| located.owner == name)
            .collect::<Vec<_>>();
        if !located.is_empty() {
            line(&mut out, "    // Initialize located variable pointers");
            for (index, located) in located {
                line(
                    &mut out,
                    &format!(
                        "    locatedVars[{index}].pointer = {}.raw_ptr();",
                        located.name
                    ),
                );
            }
        }
        line(&mut out, "}");
        line(&mut out, "");
        line(&mut out, &format!("void Program_{name}::run() {{"));
        self.statements(&program.body, &context, "    ", &mut out)?;
        line(&mut out, "}");
        line(&mut out, "");
        line(&mut out, "}  // namespace strucpp");
        Ok(out)
    }

    fn statements(
        &mut self,
        statements: &[Statement],
        context: &ExpressionContext,
        indent: &str,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        for statement in statements {
            match statement {
                Statement::Assignment(assignment) => {
                    if let Expression::Variable(variable) = &assignment.target {
                        let name = iec_ident(&variable.name);
                        if context.external_composites.contains_key(&name) {
                            self.emit_composite_global_write(
                                variable,
                                &assignment.value,
                                context,
                                indent,
                                out,
                            )?;
                            continue;
                        }
                        let value = emit_expression(&assignment.value, context).map_err(codegen)?;
                        if variable.access_chain.is_empty()
                            && context.external_scalars.contains_key(&name)
                        {
                            let pointer = context
                                .variable_cpp_names
                                .get(&name)
                                .cloned()
                                .unwrap_or(name);
                            line(out, &format!("{indent}{pointer}->write({value});"));
                            continue;
                        }
                        let target = assignment_target(&assignment.target, context)?;
                        line(out, &format!("{indent}{target} = {value};"));
                    } else {
                        let target = assignment_target(&assignment.target, context)?;
                        let value = emit_expression(&assignment.value, context).map_err(codegen)?;
                        line(out, &format!("{indent}{target} = {value};"));
                    }
                }
                Statement::FunctionCall(call) => {
                    if context
                        .function_block_instances
                        .contains_key(&iec_ident(&call.function_name))
                    {
                        self.emit_fb_invocation(call, context, indent, out)?;
                    } else {
                        line(
                            out,
                            &format!(
                                "{indent}{};",
                                super::expression::emit_call(call, context).map_err(codegen)?
                            ),
                        );
                    }
                }
                Statement::If(if_statement) => {
                    line(
                        out,
                        &format!(
                            "{indent}if ({}) {{",
                            emit_expression(&if_statement.condition, context).map_err(codegen)?
                        ),
                    );
                    self.statements(
                        &if_statement.then_statements,
                        context,
                        &format!("{indent}    "),
                        out,
                    )?;
                    for clause in &if_statement.elsif_clauses {
                        line(
                            out,
                            &format!(
                                "{indent}}} else if ({}) {{",
                                emit_expression(&clause.condition, context).map_err(codegen)?
                            ),
                        );
                        self.statements(
                            &clause.statements,
                            context,
                            &format!("{indent}    "),
                            out,
                        )?;
                    }
                    if !if_statement.else_statements.is_empty() {
                        line(out, &format!("{indent}}} else {{"));
                        self.statements(
                            &if_statement.else_statements,
                            context,
                            &format!("{indent}    "),
                            out,
                        )?;
                    }
                    line(out, &format!("{indent}}}"));
                }
                Statement::While(while_statement) => {
                    let label = self.enter_loop();
                    line(
                        out,
                        &format!(
                            "{indent}while ({}) {{",
                            emit_expression(&while_statement.condition, context)
                                .map_err(codegen)?
                        ),
                    );
                    self.statements(
                        &while_statement.body,
                        context,
                        &format!("{indent}    "),
                        out,
                    )?;
                    line(out, &format!("{indent}}}"));
                    self.leave_loop(label, indent, out);
                }
                Statement::Repeat(repeat) => {
                    let label = self.enter_loop();
                    line(out, &format!("{indent}do {{"));
                    self.statements(&repeat.body, context, &format!("{indent}    "), out)?;
                    line(
                        out,
                        &format!(
                            "{indent}}} while (!({}));",
                            emit_expression(&repeat.condition, context).map_err(codegen)?
                        ),
                    );
                    self.leave_loop(label, indent, out);
                }
                Statement::For(for_statement) => {
                    let label = self.enter_loop();
                    let variable = iec_ident(&for_statement.control_variable);
                    let start = emit_expression(&for_statement.start, context).map_err(codegen)?;
                    let end = emit_expression(&for_statement.end, context).map_err(codegen)?;
                    let step = for_statement
                        .step
                        .as_ref()
                        .and_then(literal_i64)
                        .unwrap_or(1);
                    let comparison = if step < 0 { ">=" } else { "<=" };
                    let increment = if step == 1 {
                        format!("{variable}++")
                    } else {
                        format!("{variable} += {step}")
                    };
                    line(
                        out,
                        &format!(
                            "{indent}for ({variable} = {start}; {variable} {comparison} {end}; {increment}) {{"
                        ),
                    );
                    self.statements(&for_statement.body, context, &format!("{indent}    "), out)?;
                    line(out, &format!("{indent}}}"));
                    self.leave_loop(label, indent, out);
                }
                Statement::Exit(_) => {
                    if let Some(label) = self.loop_stack.last().copied() {
                        self.used_loop_labels.insert(label);
                        line(out, &format!("{indent}goto __strucpp_loop_exit_{label};"));
                    } else {
                        line(out, &format!("{indent}break;"));
                    }
                }
                Statement::Return(_) => {
                    if let Some(function_name) = context.function_name.as_deref() {
                        line(out, &format!("{indent}return {function_name}_result;"));
                    } else {
                        line(out, &format!("{indent}return;"));
                    }
                }
                Statement::Delete { pointer, .. } => {
                    line(
                        out,
                        &format!(
                            "{indent}strucpp::iec_delete({});",
                            emit_expression(pointer, context).map_err(codegen)?
                        ),
                    );
                }
                Statement::ExternalCode { code, .. } => {
                    for source_line in code.lines() {
                        line(out, &format!("{indent}{source_line}"));
                    }
                }
                Statement::Empty(_) => line(out, ""),
                Statement::Case(case_statement) => {
                    self.case_statement(case_statement, context, indent, out)?;
                }
            }
        }
        Ok(())
    }

    fn emit_composite_global_write(
        &mut self,
        variable: &crate::frontend::ast::VariableExpression,
        value_expr: &Expression,
        context: &ExpressionContext,
        indent: &str,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        let name = iec_ident(&variable.name);
        let type_name = context
            .external_composites
            .get(&name)
            .cloned()
            .ok_or_else(|| codegen(format!("unknown composite external {name}")))?;
        let pointer = context
            .variable_cpp_names
            .get(&name)
            .cloned()
            .unwrap_or(name);
        let value = emit_expression(value_expr, context).map_err(codegen)?;
        let temp = format!("__gwv_{}", self.temp_var_counter);
        self.temp_var_counter += 1;
        line(out, &format!("{indent}auto {temp} = {value};"));

        if let Some(crate::frontend::ast::AccessStep::Field(bit)) = variable.access_chain.last() {
            if bit.chars().all(|ch| ch.is_ascii_digit()) {
                let base_chain = &variable.access_chain[..variable.access_chain.len() - 1];
                let lvalue = render_access_tail(
                    "(*__glk)".to_owned(),
                    Some(type_name.clone()),
                    base_chain,
                    context,
                )
                .map_err(codegen)?;
                line(
                    out,
                    &format!(
                        "{indent}{pointer}->with_lock([&](auto* __glk){{ {lvalue} = ({lvalue} & ~(1ULL << {bit})) | (({temp} ? 1ULL : 0ULL) << {bit}); }});"
                    ),
                );
                return Ok(());
            }
        }

        let lvalue = render_access_tail(
            "(*__glk)".to_owned(),
            Some(type_name),
            &variable.access_chain,
            context,
        )
        .map_err(codegen)?;
        line(
            out,
            &format!("{indent}{pointer}->with_lock([&](auto* __glk){{ {lvalue} = {temp}; }});"),
        );
        Ok(())
    }

    fn emit_fb_invocation(
        &mut self,
        call: &crate::frontend::ast::FunctionCallExpression,
        context: &ExpressionContext,
        indent: &str,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        let instance_key = iec_ident(&call.function_name);
        let instance = context
            .variable_cpp_names
            .get(&instance_key)
            .cloned()
            .unwrap_or_else(|| instance_key.clone());
        let fb_type = context
            .function_block_instances
            .get(&instance_key)
            .ok_or_else(|| codegen(format!("unknown function-block instance {instance_key}")))?;
        if context.external_composites.contains_key(&instance_key) {
            return Err(codegen(format!(
                "Shared global '{}' is a function-block instance and is invoked in a program body. Calling a shared function-block global is not yet supported in the mutex-based shared-global model — scalar globals only for now.",
                call.function_name
            )));
        }
        let (input_names, inout_names) = self
            .function_block_interface_names(fb_type)
            .ok_or_else(|| codegen(format!("unknown function-block type {fb_type}")))?;

        let library_declares_en = self
            .libraries
            .iter()
            .flat_map(|archive| archive.manifest.function_blocks.iter())
            .find(|fb| iec_ident(&fb.name) == *fb_type)
            .is_some_and(|fb| fb.inputs.iter().any(|input| iec_ident(&input.name) == "EN"));
        let mut en_expression = None;
        let mut eno_target = None;
        let mut filtered = Vec::new();
        for argument in &call.arguments {
            let name = argument.name.as_deref().map(iec_ident);
            match (name.as_deref(), argument.is_output) {
                (Some("EN"), false) => {
                    en_expression =
                        Some(emit_expression(&argument.value, context).map_err(codegen)?);
                    if library_declares_en {
                        filtered.push(argument);
                    }
                }
                (Some("ENO"), true) => eno_target = Some(&argument.value),
                _ => filtered.push(argument),
            }
        }

        let mut positional = 0usize;
        for argument in &filtered {
            if argument.is_output {
                continue;
            }
            let field = if let Some(name) = argument.name.as_deref() {
                iec_ident(name)
            } else if let Some(name) = input_names.get(positional) {
                positional += 1;
                name.clone()
            } else {
                line(
                    out,
                    &format!(
                        "{indent}// WARNING: positional argument {positional} could not be resolved"
                    ),
                );
                positional += 1;
                continue;
            };
            line(
                out,
                &format!(
                    "{indent}{instance}.{field} = {};",
                    emit_expression(&argument.value, context).map_err(codegen)?
                ),
            );
        }

        if let Some(en_expression) = en_expression {
            let body_indent = format!("{indent}    ");
            line(out, &format!("{indent}if ({en_expression}) {{"));
            line(out, &format!("{body_indent}{instance}();"));
            line(out, &format!("{body_indent}{instance}.ENO = true;"));
            if let Some(target) = eno_target {
                self.emit_capture_to_lvalue(target, "true", context, &body_indent, out)?;
            }
            line(out, &format!("{indent}}} else {{"));
            line(out, &format!("{body_indent}{instance}.ENO = false;"));
            if let Some(target) = eno_target {
                self.emit_capture_to_lvalue(target, "false", context, &body_indent, out)?;
            }
            line(out, &format!("{indent}}}"));
        } else {
            line(out, &format!("{indent}{instance}();"));
            line(out, &format!("{indent}{instance}.ENO = true;"));
            if let Some(target) = eno_target {
                self.emit_capture_to_lvalue(target, "true", context, indent, out)?;
            }
        }

        for argument in &filtered {
            let Some(name) = argument.name.as_deref().map(iec_ident) else {
                continue;
            };
            if !argument.is_output && inout_names.contains(&name) {
                self.emit_capture_to_lvalue(
                    &argument.value,
                    &format!("{instance}.{name}"),
                    context,
                    indent,
                    out,
                )?;
            }
        }
        for argument in &filtered {
            if !argument.is_output {
                continue;
            }
            let Some(name) = argument.name.as_deref().map(iec_ident) else {
                continue;
            };
            self.emit_capture_to_lvalue(
                &argument.value,
                &format!("{instance}.{name}"),
                context,
                indent,
                out,
            )?;
        }
        Ok(())
    }

    fn function_block_interface_names(
        &self,
        fb_type: &str,
    ) -> Option<(Vec<String>, HashSet<String>)> {
        if let Some(fb) = self
            .ast
            .function_blocks
            .iter()
            .find(|candidate| iec_ident(&candidate.name) == *fb_type)
        {
            let input_names = fb
                .var_blocks
                .iter()
                .filter(|block| block.block_type == VarBlockType::Input)
                .flat_map(|block| block.declarations.iter())
                .flat_map(|declaration| declaration.names.iter())
                .map(|name| iec_ident(name))
                .collect::<Vec<_>>();
            let inout_names = fb
                .var_blocks
                .iter()
                .filter(|block| block.block_type == VarBlockType::InOut)
                .flat_map(|block| block.declarations.iter())
                .flat_map(|declaration| declaration.names.iter())
                .map(|name| iec_ident(name))
                .collect::<HashSet<_>>();
            return Some((input_names, inout_names));
        }

        self.libraries
            .iter()
            .flat_map(|archive| archive.manifest.function_blocks.iter())
            .find(|fb| iec_ident(&fb.name) == *fb_type)
            .map(|fb| {
                (
                    fb.inputs
                        .iter()
                        .map(|input| iec_ident(&input.name))
                        .collect::<Vec<_>>(),
                    fb.inouts
                        .iter()
                        .map(|inout| iec_ident(&inout.name))
                        .collect::<HashSet<_>>(),
                )
            })
    }

    fn emit_capture_to_lvalue(
        &self,
        target: &Expression,
        source: &str,
        context: &ExpressionContext,
        indent: &str,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        if let Expression::Variable(variable) = target {
            let name = iec_ident(&variable.name);
            let pointer = context
                .variable_cpp_names
                .get(&name)
                .cloned()
                .unwrap_or_else(|| name.clone());
            if let Some(type_name) = context.external_composites.get(&name) {
                let lvalue = render_access_tail(
                    "(*__glk)".to_owned(),
                    Some(type_name.clone()),
                    &variable.access_chain,
                    context,
                )
                .map_err(codegen)?;
                line(
                    out,
                    &format!(
                        "{indent}{pointer}->with_lock([&](auto* __glk){{ {lvalue} = {source}; }});"
                    ),
                );
                return Ok(());
            }
            if variable.access_chain.is_empty() && context.external_scalars.contains_key(&name) {
                line(out, &format!("{indent}{pointer}->write({source});"));
                return Ok(());
            }
        }
        let target = assignment_target(target, context)?;
        line(out, &format!("{indent}{target} = {source};"));
        Ok(())
    }

    fn case_statement(
        &mut self,
        statement: &CaseStatement,
        context: &ExpressionContext,
        indent: &str,
        out: &mut String,
    ) -> Result<(), CodeGenError> {
        line(
            out,
            &format!(
                "{indent}switch ({}) {{",
                emit_expression(&statement.selector, context).map_err(codegen)?
            ),
        );
        let inner_indent = format!("{indent}    ");
        let body_indent = format!("{inner_indent}    ");
        for case in &statement.cases {
            for label in &case.labels {
                if let Some(end) = &label.end {
                    if let (Some(start_value), Some(end_value)) =
                        (constant_i64(Some(&label.start)), constant_i64(Some(end)))
                    {
                        for value in start_value..=end_value {
                            line(out, &format!("{inner_indent}case {value}:"));
                        }
                    } else {
                        line(
                            out,
                            &format!(
                                "{inner_indent}case {}: // range to {}",
                                emit_expression(&label.start, context).map_err(codegen)?,
                                emit_expression(end, context).map_err(codegen)?
                            ),
                        );
                    }
                } else {
                    line(
                        out,
                        &format!(
                            "{inner_indent}case {}:",
                            emit_expression(&label.start, context).map_err(codegen)?
                        ),
                    );
                }
            }
            self.statements(&case.statements, context, &body_indent, out)?;
            line(out, &format!("{body_indent}break;"));
        }
        if !statement.else_statements.is_empty() {
            line(out, &format!("{inner_indent}default:"));
            self.statements(&statement.else_statements, context, &body_indent, out)?;
            line(out, &format!("{body_indent}break;"));
        }
        line(out, &format!("{indent}}}"));
        Ok(())
    }

    fn enter_loop(&mut self) -> usize {
        let label = self.loop_counter;
        self.loop_counter += 1;
        self.loop_stack.push(label);
        label
    }

    fn leave_loop(&mut self, label: usize, indent: &str, out: &mut String) {
        self.loop_stack.pop();
        if self.used_loop_labels.remove(&label) {
            line(out, &format!("{indent}__strucpp_loop_exit_{label}: ;"));
        }
    }

    fn scoped_types(&self, blocks: &[VarBlock]) -> TypeRegistry {
        let mut types = self.types.clone();
        types.register_block_constants(blocks);
        types
    }

    fn expression_context(
        &self,
        program: &ProgramDeclaration,
    ) -> Result<ExpressionContext, CodeGenError> {
        self.context_for_blocks(&program.var_blocks, None)
    }

    fn function_block_context(
        &self,
        function_block: &FunctionBlockDeclaration,
        extra_blocks: &[VarBlock],
        function_name: Option<&str>,
    ) -> Result<ExpressionContext, CodeGenError> {
        let mut blocks = Vec::new();
        self.collect_function_block_hierarchy_blocks(function_block, &mut blocks);
        blocks.extend_from_slice(extra_blocks);
        let mut context = self.context_for_blocks(&blocks, function_name)?;
        context.current_fb_name = Some(iec_ident(&function_block.name));
        context.current_fb_extends = function_block.extends.as_deref().map(iec_ident);
        Ok(context)
    }

    fn collect_function_block_hierarchy_blocks(
        &self,
        function_block: &FunctionBlockDeclaration,
        blocks: &mut Vec<VarBlock>,
    ) {
        if let Some(parent_name) = function_block.extends.as_deref() {
            if let Some(parent) = self
                .ast
                .function_blocks
                .iter()
                .find(|candidate| iec_ident(&candidate.name) == iec_ident(parent_name))
            {
                self.collect_function_block_hierarchy_blocks(parent, blocks);
            }
        }
        blocks.extend(function_block.var_blocks.iter().cloned());
    }

    fn context_for_blocks(
        &self,
        blocks: &[crate::frontend::ast::VarBlock],
        function_name: Option<&str>,
    ) -> Result<ExpressionContext, CodeGenError> {
        let types = self.scoped_types(blocks);
        let mut context = ExpressionContext {
            function_name: function_name.map(str::to_owned),
            types: types.clone(),
            ..ExpressionContext::default()
        };
        let mut fb_types = self
            .ast
            .function_blocks
            .iter()
            .map(|function_block| iec_ident(&function_block.name))
            .collect::<HashSet<_>>();
        fb_types.extend(self.library_fb_types.iter().cloned());
        for (name, type_name) in &self.library_globals {
            context
                .variable_types
                .entry(name.clone())
                .or_insert_with(|| type_name.clone());
        }
        for block in blocks {
            for declaration in &block.declarations {
                let type_name = iec_ident(&declaration.variable_type.name);
                let expression_type = if declaration.variable_type.array_dimensions.is_empty() {
                    type_name.clone()
                } else {
                    format!(
                        "@ARRAY:{}",
                        declaration
                            .variable_type
                            .element_type_name
                            .as_deref()
                            .map(iec_ident)
                            .unwrap_or_default()
                    )
                };
                for name in &declaration.names {
                    let variable = iec_ident(name);
                    context
                        .variable_types
                        .insert(variable.clone(), expression_type.clone());
                    let emitted = if block.block_type == VarBlockType::External {
                        variable.clone()
                    } else {
                        types.member_cpp_name(name, &type_name)
                    };
                    if emitted != variable {
                        context.variable_cpp_names.insert(variable, emitted);
                    }
                }
                if fb_types.contains(&type_name) {
                    for name in &declaration.names {
                        context
                            .function_block_instances
                            .insert(iec_ident(name), type_name.clone());
                    }
                }
                if block.block_type != VarBlockType::External {
                    continue;
                }
                let ty = cpp_type_with_registry(&declaration.variable_type, &self.types)
                    .map_err(codegen)?;
                let composite = fb_types.contains(&type_name) || types.is_composite(&type_name);
                for name in &declaration.names {
                    let name = iec_ident(name);
                    if composite {
                        context.external_composites.insert(name, type_name.clone());
                    } else {
                        context.external_scalars.insert(name, ty.clone());
                    }
                }
            }
        }
        Ok(context)
    }

    fn external_vars(
        &self,
        blocks: &[crate::frontend::ast::VarBlock],
    ) -> Result<Vec<(String, String)>, CodeGenError> {
        let types = self.scoped_types(blocks);
        let mut externals = Vec::new();
        for block in blocks {
            if block.block_type != VarBlockType::External {
                continue;
            }
            for declaration in &block.declarations {
                let ty =
                    cpp_type_with_registry(&declaration.variable_type, &types).map_err(codegen)?;
                for name in &declaration.names {
                    externals.push((iec_ident(name), ty.clone()));
                }
            }
        }
        Ok(externals)
    }

    fn program_externals(
        &self,
        program: &ProgramDeclaration,
    ) -> Result<Vec<(String, String)>, CodeGenError> {
        self.external_vars(&program.var_blocks)
    }

    fn located_range(&self, owner: &str) -> Option<(usize, usize)> {
        let mut first = None;
        let mut count = 0;
        for (index, located) in self.located.iter().enumerate() {
            if located.owner == owner {
                first.get_or_insert(index);
                count += 1;
            }
        }
        first.map(|offset| (offset, count))
    }
}

fn assignment_target(
    expression: &Expression,
    context: &ExpressionContext,
) -> Result<String, CodeGenError> {
    let Expression::Variable(variable) = expression else {
        return Err(unsupported("non-variable assignment target"));
    };
    if !variable.access_chain.is_empty() {
        return emit_expression(expression, context).map_err(codegen);
    }
    if context
        .function_name
        .as_deref()
        .is_some_and(|name| name == iec_ident(&variable.name))
    {
        return Ok(format!("{}_result", iec_ident(&variable.name)));
    }
    let name = iec_ident(&variable.name);
    Ok(context
        .variable_cpp_names
        .get(&name)
        .cloned()
        .unwrap_or(name))
}

