#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SourceSpan {
    pub file: String,
    pub start_line: usize,
    pub end_line: usize,
    pub start_col: usize,
    pub end_col: usize,
}

impl SourceSpan {
    pub fn new(
        file: impl Into<String>,
        start_line: usize,
        end_line: usize,
        start_col: usize,
        end_col: usize,
    ) -> Self {
        Self {
            file: file.into(),
            start_line,
            end_line,
            start_col,
            end_col,
        }
    }
}

