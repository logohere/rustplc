#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Token {
    pub kind: TokenKind,
    pub image: String,
    pub span: SourceSpan,
}

impl Token {
    pub fn new(kind: TokenKind, image: impl Into<String>, span: SourceSpan) -> Self {
        Self {
            kind,
            image: image.into(),
            span,
        }
    }
}
